#!/usr/bin/env python3
"""Independent Python integer semantics: SMT-LIB fixed-size BV operators.
No MoonBTOR evaluator/circuit/solver is imported. Deterministic vectors.
"""
from pathlib import Path
import itertools, json, random
ROOT = Path(__file__).resolve().parents[1]
OPS = 'udiv urem sdiv srem smod rol ror uaddo saddo usubo ssubo umulo smulo sdivo'.split()
PRED = set('uaddo saddo usubo ssubo umulo smulo sdivo'.split())
def signed(a,w): return a-(1<<w) if a & (1<<(w-1)) else a
def evaluate(op,a,b,w):
    m=(1<<w)-1; x,y=signed(a,w),signed(b,w)
    q = ((abs(x)//abs(y)) * (-1 if (x<0)!=(y<0) else 1)) if y else (-1 if x>=0 else 1)
    r = x-q*y if y else x
    k=b%w
    return {
        'udiv': lambda: a//b if b else m, 'urem': lambda: a%b if b else a,
        'sdiv': lambda:q, 'srem':lambda:r, 'smod':lambda:x%y if y else x,
        'rol':lambda: (a<<k)|(a>>(w-k)), 'ror':lambda:(a>>k)|(a<<(w-k)),
        'uaddo':lambda:a+b>m, 'usubo':lambda:a<b, 'umulo':lambda:a*b>m,
        'saddo':lambda:not(-(1<<(w-1))<=x+y<(1<<(w-1))),
        'ssubo':lambda:not(-(1<<(w-1))<=x-y<(1<<(w-1))),
        'smulo':lambda:not(-(1<<(w-1))<=x*y<(1<<(w-1))),
        'sdivo':lambda:x==-(1<<(w-1)) and y==-1,
    }[op]() & (1 if op in PRED else m)

def main():
    lines=['// Generated by tools/generate_standard_oracles.py; independent integer specification.']
    count=0; symbolic=0
    for op in OPS:
      for w in [1,3,32,64]:
        m=(1<<w)-1
        pairs=list(itertools.product(range(1<<w),repeat=2)) if w<=3 else list(itertools.product([0,1,(1<<(w-1))-1,1<<(w-1),m],repeat=2))
        if w>3:
          rng=random.Random(730+w)
          pairs += [(rng.getrandbits(w),rng.getrandbits(w)) for _ in range(8)]
        rows=[f'    ({a}UL,{b}UL,{evaluate(op,a,b,w)}UL),' for a,b in pairs]
        count+=len(rows)
        symbolic+=len(rows) if w<=3 else 0
        outsort=2 if op in PRED else 1
        model=f'1 sort bitvec {w}\n2 sort bitvec 1\n3 input 1 a\n4 input 1 b\n5 {op} {outsort} 3 4\n6 output 5\n7 constd {outsort} \\{{expected}}\n8 eq 2 5 7\n9 bad 8\n10 constd 1 \\{{a}}\n11 eq 2 3 10\n12 constraint 11\n13 constd 1 \\{{b}}\n14 eq 2 4 13\n15 constraint 14'
        literal=json.dumps(model).replace('\\\\{','\\{')
        body='''
    if WIDTH <= 3 {
      let q = model.query(0).unwrap()
      match q.formula().solve() {
        Satisfiable(bits) => { ignore(q.decode_typed(bits).unwrap()) }
        _ => fail("expected satisfiable oracle")
      }
      let wrong = @moonbtor.parse(source.replace_all(old="8 eq",new="8 neq")).unwrap()
      assert_true(wrong.query(0).unwrap().formula().solve() is Unsatisfiable)
    }
'''.replace('WIDTH',str(w))
        lines.append(f'''///|
test "standard oracle {op} width {w}" {{
  let rows = [
{chr(10).join(rows)}
  ]
  for (a,b,expected) in rows {{
    let source = {literal}
    let model = @moonbtor.parse(source).unwrap()
    assert_eq(model.observe({{state:[],inputs:[a,b]}}).unwrap().outputs,[expected])
{body}
  }}
}}''')
    (ROOT/'standard_oracle_test.mbt').write_text('\n\n'.join(lines)+'\n',encoding='utf-8')
    print(json.dumps({'standard_integer_samples':count,'symbolic_sat_unsat_pairs':symbolic,'test_groups':len(OPS)*4}))
if __name__=='__main__':main()
