#!/usr/bin/env python3
"""Independent stdlib oracle. Regenerates checked-in MoonBit differential tests.
No MoonBit source, evaluator, solver or downloaded test vectors are used.
"""
from pathlib import Path
from itertools import product
import random
ROOT=Path(__file__).resolve().parents[1]

def signed(x,w):
    return x-(1<<w) if x & (1<<(w-1)) else x

def value(op,a,b,w):
    m=(1<<w)-1
    s,t=signed(a,w),signed(b,w)
    operations={
        'not':lambda:~a, 'neg':lambda:-a, 'inc':lambda:a+1,'dec':lambda:a-1,
        'redand':lambda:a==m,'redor':lambda:a!=0,'redxor':lambda:bin(a).count('1')%2,
        'and':lambda:a&b,'or':lambda:a|b,'xor':lambda:a^b,
        'nand':lambda:~(a&b),'nor':lambda:~(a|b),'xnor':lambda:~(a^b),
        'add':lambda:a+b,'sub':lambda:a-b,'mul':lambda:a*b,
        'eq':lambda:a==b,'neq':lambda:a!=b,
        'ult':lambda:a<b,'ulte':lambda:a<=b,'ugt':lambda:a>b,'ugte':lambda:a>=b,
        'slt':lambda:s<t,'slte':lambda:s<=t,'sgt':lambda:s>t,'sgte':lambda:s>=t,
        'sll':lambda:0 if b>=w else a<<b,'srl':lambda:0 if b>=w else a>>b,
        'sra':lambda:(-1 if s<0 else 0) if b>=w else s>>b,
        'iff':lambda:a==b,'implies':lambda:a==0 or b!=0,
    }
    return int(operations[op]())&m

def bitvectors():
    unary=['not','neg','inc','dec','redand','redor','redxor']
    binary=['and','or','xor','nand','nor','xnor','add','sub','mul','eq','neq','ult','ulte','ugt','ugte','slt','slte','sgt','sgte','sll','srl','sra','iff','implies']
    boolean=set(['eq','neq','ult','ulte','ugt','ugte','slt','slte','sgt','sgte','redand','redor','redxor','iff','implies'])
    lines=['// Generated by tools/generate_oracles.py; independent Python integer oracle.']
    count=0
    for op in unary+binary:
        w=1 if op in ['iff','implies'] else 3
        pairs=list(product(range(1<<w),repeat=2)) if op in binary else [(a,0) for a in range(1<<w)]
        # Also exercise exact UInt32 boundaries with bounded, independent values.
        groups=[(w,pairs)]
        if op not in ['iff','implies']:
            edge=[0,1,31,32,0x7fffffff,0x80000000,0xffffffff]
            groups.append((32,list(product(edge,repeat=2)) if op in binary else [(a,0) for a in edge]))
        for width,cases in groups:
            result_sort='2' if op in boolean else '1'
            operands='3' if op in unary else '3 4'
            rows=','.join('(%dUL,%dUL,%dUL)'%(a,b,value(op,a,b,width)) for a,b in cases)
            lines.append('test "Python oracle %s width%d concrete and symbolic" {\n  let rows = [%s]\n  for (a,b,expected) in rows {\n    let source = "1 sort bitvec %d\\n2 sort bitvec 1\\n3 input 1 a\\n4 input 1 b\\n5 %s %s %s\\n6 output 5\\n7 constd %s \\{expected}\\n8 eq 2 5 7\\n9 bad 8\\n10 constd 1 \\{a}\\n11 eq 2 3 10\\n12 constraint 11\\n13 constd 1 \\{b}\\n14 eq 2 4 13\\n15 constraint 14"\n    let model = @moonbtor.parse(source).unwrap()\n    assert_eq(model.observe({state:[],inputs:[a,b]}).unwrap().outputs,[expected])\n    assert_true(model.query(0).unwrap().formula().solve() is Satisfiable(_))\n    let wrong = @moonbtor.parse(source.replace_all(old="8 eq", new="8 neq")).unwrap()\n    assert_true(wrong.query(0).unwrap().formula().solve() is Unsatisfiable)\n  }\n}'%(op,width,rows,width,op,result_sort,operands,result_sort))
            count+=len(cases)
    (ROOT/'oracle_vectors_test.mbt').write_text('\n\n'.join(lines)+'\n',encoding='utf-8')
    return count

def sat():
    rng=random.Random(1729)
    lines=['// Generated independently by Python exhaustive truth assignments.']
    for i in range(180):
        n=rng.randrange(0,7)
        clauses=[[rng.choice([-1,1])*rng.randrange(1,n+1) for _ in range(rng.randrange(0,5))] for _ in range(rng.randrange(0,13))] if n else ([[]] if i%2 else [])
        expected=any(all(any(bits[abs(l)-1]==(l>0) for l in c) for c in clauses) for bits in product([False,True],repeat=n))
        text='p cnf %d %d\n'%(n,len(clauses))+''.join(' '.join(map(str,c))+' 0\n' for c in clauses)
        escaped=text.replace('\n','\\n')
        lines.append('test "independent SAT enumeration %d" {\n let f = @moonbtor.parse_dimacs("%s").unwrap()\n match f.solve() {\n Satisfiable(bits) => { assert_true(%s); assert_true(f.accepts(bits)) }\n Unsatisfiable => assert_true(%s)\n Indeterminate(_) => fail("unexpected oracle resource exhaustion")\n }\n}'%(i,escaped,str(expected).lower(),str(not expected).lower()))
    (ROOT/'oracle_sat_test.mbt').write_text('\n\n'.join(lines)+'\n',encoding='utf-8')

def bmc():
    lines=['// Python reachable-set exploration; no SAT or MoonBit evaluator used.']
    for initial,target,forbidden in product([0,3],range(8),[-1,4]):
        reachable={initial}
        found=None
        for depth in range(6):
            reachable={x for x in reachable if x!=forbidden}
            if target in reachable:
                found=depth;break
            reachable={(x+u)&7 for x in reachable for u in [0,1]}
        source='1 sort bitvec 3\n2 sort bitvec 1\n3 state 1 x\n4 input 1 u\n5 constd 1 %d\n6 init 1 3 5\n7 add 1 3 4\n8 next 1 3 7\n9 constd 1 %d\n10 eq 2 3 9\n11 bad 10\n12 constd 1 1\n13 ulte 2 4 12\n14 constraint 13'%(initial,target)
        if forbidden>=0:source+='\n15 constd 1 %d\n16 neq 2 3 15\n17 constraint 16'%forbidden
        escaped=source.replace('\n','\\n')
        result='assert_eq(result,@moonbtor.BoundedSafe(5))' if found is None else 'match result { Counterexample(t) => { assert_eq(t.frames.length(),%d); assert_true(model.replay(t) is Ok(_)) }; _ => fail("expected reachable bad state") }'%(found+1)
        lines.append('test "Python reachability init%d target%d forbidden%d" {\n let model = @moonbtor.parse("%s").unwrap()\n let result = model.check(5).unwrap()\n %s\n}'%(initial,target,forbidden,escaped,result))
    (ROOT/'oracle_bmc_test.mbt').write_text('\n\n'.join(lines)+'\n',encoding='utf-8')

if __name__=='__main__':
    count=bitvectors();sat();bmc()
    print('Generated %d concrete/symbolic vector cases, 180 SAT instances and 32 transition systems.'%count)
